/* Includes----------------------------------------------------------*/
#include "stm32f446xx_timer_mort.h"



/* MACRO definitions----------------------------------------------------------*/

// REGISTER ADDRESSES:
// Timer 3: internal counter for the 0.1-second waiting period.
#define TIMER3_BASE_ADDRESS  ((uint32_t)0x40000400)
#define TIMER3_PSC_REGISTER  (TIMER3_BASE_ADDRESS + 0x28) // Prescaler: controls counting speed.
#define TIMER3_ARR_REGISTER  (TIMER3_BASE_ADDRESS + 0x2C) // Auto-reload: counter's maximum value.
#define TIMER3_EGR_REGISTER  (TIMER3_BASE_ADDRESS + 0x14) // Apply the prescaler and reset the counter.
#define TIMER3_SR_REGISTER   (TIMER3_BASE_ADDRESS + 0x10) // Read or clear event flags.
#define TIMER3_CR1_REGISTER  (TIMER3_BASE_ADDRESS + 0x00) // Control and start the counter.

// FLAGS:

// EGR: restart the counting period.
#define TIMER3_EGR_UPDATE_GENERATE       0x01 // Bit 0: generate an update, resetting the counter and prescaler.

// CR1: start counting.
#define TIMER3_CR1_COUNTER_ENABLE        0x01 // Bit 0: enable the counter.

// SR: check whether the counting period finished.
#define TIMER3_SR_OVERFLOW_FLAG_MASK     0x01 // Bit 0: update flag; set on overflow from ARR to 0, or by a generated update.

// Period of timer
#define PERIOD                           (uint32_t)4999 // (999 + 1) counts × 0.1 ms = 0.1 s.


/* function definitions-------------------------------------------------------*/

// For part 2 we only need timer as a reference not trigger, or interrupt
void initTimer3 (void){

  //step
  // make clock like part 1
  // the supplied clock give timer 3 = 90 MHz, we need to slow down
  // PSC == use to slow down counitng == set PSC to 8999 so that  90,000,000 / (8999 + 1) == 10000 == 10KHz
  // ARR == set when counter restart == FOR EXAMPLE set to 4999 so it counts from 0-4999 = 5000 counts == 5000/10000 = 0.5 s (10000 counts/second, set recount to 5000, so 0.5 second)
  
  volatile uint32_t * reg_pointer;

  //initialize timer that is reference
  RCC_APB1PeriphClockCmd(RCC_APB1Periph_TIM3, ENABLE);

  //PSC
  reg_pointer = (volatile uint32_t *) TIMER3_PSC_REGISTER;
  *reg_pointer = 8999;

  //ARR 
  reg_pointer = (volatile uint32_t*) TIMER3_ARR_REGISTER;
  *reg_pointer = (uint32_t)PERIOD;


  //Apply the prescaler setting and initialize the counter 
  reg_pointer = (volatile uint32_t*) TIMER3_EGR_REGISTER;
  *reg_pointer = (uint32_t)TIMER3_EGR_UPDATE_GENERATE;


  //Clear event flags generated during initialization 
  reg_pointer = (volatile uint32_t*) TIMER3_SR_REGISTER;
  *reg_pointer = (uint32_t)0;

  
  //Start counting 
  reg_pointer = (volatile uint32_t*) TIMER3_CR1_REGISTER;
  *reg_pointer = *reg_pointer | (uint32_t)TIMER3_CR1_COUNTER_ENABLE;
}


void restartTimer3 (void)
{
  // Reset the counter and prescaler to begin a new counting period.
  // Clear old event flags + the update flag generated by the reset.
  // DO: start counting for x second from now

  volatile uint32_t * reg_pointer;

  // Apply the prescaler setting and initialize the counter 
  reg_pointer = (volatile uint32_t*) TIMER3_EGR_REGISTER;
  *reg_pointer = (uint32_t)TIMER3_EGR_UPDATE_GENERATE;


  // Clear event flags generated during initialization 
  reg_pointer = (volatile uint32_t*) TIMER3_SR_REGISTER;
  *reg_pointer = (uint32_t)0;

  
  // Start counting 
  reg_pointer = (volatile uint32_t*) TIMER3_CR1_REGISTER;
  *reg_pointer = *reg_pointer | (uint32_t)TIMER3_CR1_COUNTER_ENABLE;

}


uint32_t checkTimer3Overflow(void)
{
    // Check whether the waiting period finished, and clear the flag if it did.
    // DO: check if does counting for x second finish?
    uint32_t value;
    volatile uint32_t * reg_pointer;
    
    reg_pointer = (volatile uint32_t*) TIMER3_SR_REGISTER;
    value = *reg_pointer & (uint32_t)TIMER3_SR_OVERFLOW_FLAG_MASK; // Read SR bit 0, hardware sets it when the counter passes ARR.

    if(value != 0)
    {
        
        *reg_pointer = ~((uint32_t)TIMER3_SR_OVERFLOW_FLAG_MASK); // Writing 0 clears this flag; writing 1 leaves other flags unchanged.
        return 1;
    }

    else
    {
        return 0;
    }
}








